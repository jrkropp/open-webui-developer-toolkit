def _to_dict(obj: BaseModel | dict[str, Any]) -> dict[str, Any]:
    if isinstance(obj, BaseModel):
        return obj.model_dump()
    return obj


async def _maybe_await(value: Any) -> Any:
    if asyncio.isfuture(value) or inspect.isawaitable(value):
        return await value
    return value


