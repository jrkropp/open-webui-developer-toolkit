    if cfg.WEB_SEARCH_USER_LOCATION:
        try:
            tool["user_location"] = json.loads(cfg.WEB_SEARCH_USER_LOCATION)
        except Exception:
            _logger.warning("WEB_SEARCH_USER_LOCATION is not valid JSON; ignoring.")

